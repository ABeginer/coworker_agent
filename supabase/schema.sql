-- 1. Create task_status enum (optional, or text check constraint)
CREATE TYPE public.task_status AS ENUM ('pending', 'in_progress', 'completed', 'failed');

-- 2. Create tasks table
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    status public.task_status NOT NULL DEFAULT 'pending',
    ai_output TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;

-- 4. Policies for anon / authenticated access
CREATE POLICY "Enable read access for all users" 
ON public.tasks FOR SELECT 
USING (true);

CREATE POLICY "Enable insert access for all users" 
ON public.tasks FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Enable update access for all users" 
ON public.tasks FOR UPDATE 
USING (true);

-- 5. Enable Realtime Replication on the tasks table
ALTER PUBLICATION supabase_realtime ADD TABLE public.tasks;
